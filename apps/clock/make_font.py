#!/usr/bin/env python3
"""
Renders the Clock's fonts into clock_font.h (checked in, so building the app needs no PIL):
Montserrat (SIL Open Font License 1.1, the copy that ships with LVGL), anti-aliased, 4 bits per pixel.

    python apps/clock/make_font.py [path/to/Montserrat-SemiBold.ttf]

Needs Pillow. Without a path it takes the LVGL copy in launcher/managed_components.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
LVGL = os.path.join(HERE, "..", "..", "launcher", "managed_components", "lvgl__lvgl")
ASCII = "".join(chr(c) for c in range(32, 127))
DIGITS = "0123456789:. "

# name, file, pixel size, characters
FONTS = [
    ("F_SMALL", "scripts/built_in_font/Montserrat-Medium.ttf", 18, ASCII),
    ("F_MED", "demos/multilang/assets/fonts/Montserrat-SemiBold.ttf", 26, ASCII),
    ("F_LARGE", "demos/multilang/assets/fonts/Montserrat-SemiBold.ttf", 44, ASCII),
    ("F_BIG", "demos/multilang/assets/fonts/Montserrat-SemiBold.ttf", 100, DIGITS),
    ("F_HUGE", "demos/multilang/assets/fonts/Montserrat-SemiBold.ttf", 160, DIGITS),
]


def render(path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in chars:
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")     # from the baseline
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = int(round(font.getlength(ch)))
        off = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            px = img.tobytes()
            for row in range(h):
                line = px[row * w:(row + 1) * w]
                for i in range(0, w, 2):
                    a = line[i] >> 4
                    b = line[i + 1] >> 4 if i + 1 < w else 0
                    data.append(a << 4 | b)
        glyphs.append((ord(ch), w, h, x0, y0 + ascent, adv, off))
    return ascent, descent, glyphs, data


def main():
    out = ["/* Generated by make_font.py from Montserrat (SIL Open Font License 1.1). Do not edit. */",
           "#pragma once", "#include <stdint.h>", "",
           "typedef struct { uint8_t ch, w, h; int8_t x; int16_t y; uint8_t adv; uint32_t off; } cf_glyph_t;",
           "typedef struct { const cf_glyph_t *g; int n; const uint8_t *px; int ascent, height; } cf_font_t;",
           "/* y = top of the glyph below the top of the line; px = 4-bit alpha, two pixels a byte, rows padded */", ""]
    for name, rel, size, chars in FONTS:
        path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(LVGL, rel)
        ascent, descent, glyphs, data = render(path, size, chars)
        low = name.lower()
        out.append(f"static const uint8_t {low}_px[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const cf_glyph_t {low}_g[{len(glyphs)}] = {{")
        for g in glyphs:
            out.append("    {%d,%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(f"static const cf_font_t {name} = {{ {low}_g, {len(glyphs)}, {low}_px, {ascent}, {ascent + descent} }};")
        out.append("")
        print(f"{name}: {size}px, {len(glyphs)} glyphs, {len(data)} bytes")
    with open(os.path.join(HERE, "clock_font.h"), "w", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
